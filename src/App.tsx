import { AlertTriangle, Check, Download, FileCode, Info, Link, Loader2, XCircle } from 'lucide-react';
import { useCallback, useEffect, useMemo, useState } from 'react';
import { Footprint } from '@/components/Footprint';
import { CUSTOM_PRESET, ParamsPanel } from '@/components/ParamsPanel';
import { Button } from '@/components/ui/button';
import { Switch } from '@/components/ui/switch';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Viewer3D } from '@/components/Viewer3D';
import { analyse, type Finding } from '@/lib/analysis';
import { DEFAULT_PARAMS, type JigParams, jigSource, withParams } from '@/lib/jig-params';
import { matchPin } from '@/lib/pogo-pins';
import { applyPreset, DEFAULT_PRESET_ID, PRESET_KEYS, PRESETS } from '@/lib/presets';
import { decodeShare, encodeShare } from '@/lib/share';
import { useJigRender } from '@/lib/use-jig-render';

// Editing these doesn't stop a jig from being "the TYWE3S preset".
const PRESET_IDENTITY_KEYS = PRESET_KEYS.filter(
  (k) => !['skip_pins', 'view_from_bottom', 'sit_on_board', 'clamp_tab'].includes(k),
);

function initialState() {
  const shared = decodeShare(window.location.hash);
  if (shared) return shared;
  const preset = PRESETS.find((p) => p.id === DEFAULT_PRESET_ID)!;
  return { preset: preset.id, params: applyPreset(DEFAULT_PARAMS, preset) };
}

function download(name: string, data: BlobPart, type: string) {
  const url = URL.createObjectURL(new Blob([data], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function App() {
  const [{ preset: chosenPreset, params }, setState] = useState(initialState);
  const [showPins, setShowPins] = useState(true);
  const [copied, setCopied] = useState(false);
  const render = useJigRender(params);

  // The preset still applies while its layout values are untouched.
  const presetId = useMemo(() => {
    const p = PRESETS.find((x) => x.id === chosenPreset);
    if (!p) return CUSTOM_PRESET;
    const expected = applyPreset(params, p);
    const same = PRESET_IDENTITY_KEYS.every((k) => JSON.stringify(expected[k]) === JSON.stringify(params[k]));
    return same ? p.id : CUSTOM_PRESET;
  }, [chosenPreset, params]);
  const preset = PRESETS.find((p) => p.id === presetId);

  useEffect(() => {
    history.replaceState(null, '', `#${encodeShare(presetId, params)}`);
  }, [presetId, params]);

  const set = useCallback(
    (patch: Partial<JigParams>) => setState((s) => ({ ...s, params: { ...s.params, ...patch } })),
    [],
  );
  const onPreset = useCallback((id: string) => {
    const p = PRESETS.find((x) => x.id === id);
    setState((s) => ({ preset: id, params: p ? applyPreset(s.params, p) : s.params }));
  }, []);
  const togglePin = useCallback(
    (num: number) =>
      setState((s) => {
        const skip = s.params.skip_pins;
        const next = skip.includes(num) ? skip.filter((n) => n !== num) : [...skip, num].sort((a, b) => a - b);
        return { ...s, params: { ...s.params, skip_pins: next } };
      }),
    [],
  );

  const shown = render.renderedParams ?? params;
  const analysis = render.info ? analyse(shown, render.info) : null;
  const baseName = `${preset?.id ?? 'custom'}-jig`;
  const scadText = useMemo(() => {
    const pin = matchPin(params);
    const header = [
      '// Generated by the pogo-pin programming jig generator.',
      `// Package: ${preset?.name ?? 'custom'}`,
      `// Pogo pin: ${pin?.name ?? `custom ${params.pin_barrel_d} mm barrel`}`,
    ].join('\n');
    return withParams(jigSource, params, header);
  }, [params, preset]);

  const copyLink = async () => {
    await navigator.clipboard.writeText(window.location.href);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  return (
    <div className="flex h-dvh flex-col">
      <header className="flex flex-wrap items-center gap-3 border-b border-border px-4 py-2.5">
        <div className="mr-auto">
          <h1 className="text-base font-semibold">Pogo-pin jig generator</h1>
          <p className="text-xs text-muted-foreground">
            Parametric OpenSCAD programming jigs, rendered in your browser
          </p>
        </div>
        <Button variant="ghost" size="sm" onClick={copyLink}>
          {copied ? <Check /> : <Link />} {copied ? 'Copied' : 'Share link'}
        </Button>
        <Button variant="outline" size="sm" onClick={() => download(`${baseName}.scad`, scadText, 'text/plain')}>
          <FileCode /> .scad
        </Button>
        <Button
          size="sm"
          disabled={!render.stl || render.busy}
          onClick={() => render.stl && download(`${baseName}.stl`, render.stl, 'model/stl')}
        >
          <Download /> STL
        </Button>
      </header>

      <div className="flex min-h-0 flex-1 flex-col md:flex-row">
        <aside className="max-h-[45dvh] overflow-y-auto border-b border-border md:max-h-none md:w-96 md:shrink-0 md:border-r md:border-b-0">
          <ParamsPanel params={params} set={set} presetId={presetId} onPreset={onPreset} />
        </aside>

        <main className="flex min-h-0 min-w-0 flex-1 flex-col">
          <Tabs defaultValue="3d" className="flex min-h-0 flex-1 flex-col gap-0">
            <div className="flex items-center gap-3 border-b border-border px-3 py-2">
              <TabsList>
                <TabsTrigger value="3d">3D</TabsTrigger>
                <TabsTrigger value="footprint">Footprint</TabsTrigger>
                <TabsTrigger value="scad">OpenSCAD</TabsTrigger>
              </TabsList>
              <div className="flex items-center gap-2 text-xs text-muted-foreground">
                <Switch id="show-pins" size="sm" checked={showPins} onCheckedChange={setShowPins} />
                <label htmlFor="show-pins">Show pins</label>
              </div>
              <span className="ml-auto flex items-center gap-1.5 text-xs text-muted-foreground">
                {render.busy ? (
                  <>
                    <Loader2 className="size-3.5 animate-spin" /> Rendering…
                  </>
                ) : render.error ? (
                  <span className="text-destructive">Render failed</span>
                ) : (
                  `Rendered in ${render.ms} ms`
                )}
              </span>
            </div>

            <TabsContent value="3d" className="relative min-h-64 flex-1 data-[state=inactive]:hidden" forceMount>
              <Viewer3D stl={render.stl} params={shown} info={render.info} showPins={showPins} />
            </TabsContent>
            <TabsContent value="footprint" className="min-h-64 flex-1 p-4">
              {render.info && <Footprint params={shown} info={render.info} onTogglePin={togglePin} />}
            </TabsContent>
            <TabsContent value="scad" className="min-h-0 flex-1 overflow-auto">
              <pre className="p-4 font-mono text-xs leading-relaxed whitespace-pre">{scadText}</pre>
            </TabsContent>
          </Tabs>

          <StatusPanel analysis={analysis} error={render.error} logs={render.logs} />
        </main>
      </div>
    </div>
  );
}

const ICONS = { error: XCircle, warning: AlertTriangle, info: Info } as const;
const TONES = { error: 'text-destructive', warning: 'text-amber-500', info: 'text-muted-foreground' } as const;

function StatusPanel({
  analysis,
  error,
  logs,
}: {
  analysis: ReturnType<typeof analyse> | null;
  error: string | null;
  logs: string[];
}) {
  const mm = (n: number | null) => (n === null ? '–' : `${n.toFixed(2)} mm`);
  const findings: Finding[] = error ? [{ severity: 'error', message: error }] : (analysis?.findings ?? []);
  return (
    <div className="max-h-[35dvh] overflow-y-auto border-t border-border px-4 py-3 text-xs">
      {analysis && (
        <dl className="mb-2 flex flex-wrap gap-x-6 gap-y-1">
          <Stat label="Pins" value={String(analysis.stats.usedPins)} />
          <Stat label="Closest pins" value={mm(analysis.stats.minSpacing)} />
          <Stat label="Thinnest wall" value={mm(analysis.stats.minWall)} />
          <Stat label="Tip below jig" value={mm(analysis.stats.tipBelow)} />
          <Stat label="Barrel above jig" value={mm(analysis.stats.tailAbove)} />
        </dl>
      )}
      {findings.length === 0 && analysis && (
        <p className="flex items-center gap-1.5 text-emerald-500">
          <Check className="size-3.5" /> Looks printable.
        </p>
      )}
      <ul className="grid gap-1">
        {findings.map((f) => {
          const Icon = ICONS[f.severity];
          return (
            <li key={f.message} className={`flex items-start gap-1.5 ${TONES[f.severity]}`}>
              <Icon className="mt-px size-3.5 shrink-0" /> {f.message}
            </li>
          );
        })}
      </ul>
      {error && (
        <details className="mt-2">
          <summary className="cursor-pointer text-muted-foreground">OpenSCAD output</summary>
          <pre className="mt-1 font-mono whitespace-pre-wrap">{logs.join('\n')}</pre>
        </details>
      )}
    </div>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex gap-1.5">
      <dt className="text-muted-foreground">{label}</dt>
      <dd className="font-medium tabular-nums">{value}</dd>
    </div>
  );
}
